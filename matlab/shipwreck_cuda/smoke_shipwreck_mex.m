function result = smoke_shipwreck_mex(binary)
%SMOKE_SHIPWRECK_MEX Trace one triangle; not a full shipwreck regeneration.
assert(isfile(binary),'Pass the path to a locally built MEX file.');
[folder,name,extension] = fileparts(binary);
assert(strcmp(name,'stl_raytrace_arrivals_cuda3_5_1') && ...
    strcmp(extension,['.' mexext]),'Unexpected MEX file name or platform.');
old_path = path;
cleanup_path = onCleanup(@() path(old_path)); %#ok<NASGU>
addpath(folder,'-begin');
clear stl_raytrace_arrivals_cuda3_5_1
model = struct('Points',[-1,-1,5;0,1,5;1,-1,5], ...
    'ConnectivityList',[1,2,3],'reflectivity',0.7,'scattering_coeff',1, ...
    'center_frequency',450000,'transmittance',0,'isHollow',false,'internal_scattering',0);
params = struct('f0',450000,'c',1500,'max_bounces',1,'samples_per_tri',2, ...
    'seed',uint64(20250821),'tx_cos_power',-1,'rx_cos_power',-1, ...
    'amp_type',0,'reflect_is_power',1,'max_arrivals',4096);
out = stl_raytrace_arrivals_cuda3_5_1({model},[0,0,0],[0,0,0],params);
assert(isstruct(out) && all(isfield(out,{'pos','amp','path_len','order'})), ...
    'Unexpected arrival schema.');
assert(size(out.pos,1)>0 && size(out.pos,2)==3 && ...
    all(isfinite(out.pos),'all') && all(isfinite(out.amp)) && ...
    all(out.amp>0) && all(out.path_len>0) && all(out.order==1), ...
    'The one-triangle scene did not produce valid one-bounce arrivals.');
result = struct('passed',true,'arrival_count',size(out.pos,1), ...
    'max_amplitude',max(out.amp),'path_length_m',out.path_len);
disp(result);
end
