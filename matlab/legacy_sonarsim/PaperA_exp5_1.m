rx_xyz = rx_xyz([1,arrayIndex,128],:);

[tw_db3,beam3, angles3] = plot_beam_pattern(rx_xyz, f0, ...
    'steer_angle', 0, ...
    'angle_range', [-85, 85], ...
    'angle_step', 0.1, ...
    'c', c0, ...
    'window', 'rect', ...
    'plot_type', 'rect', ...
    'dyn_range', 60);
%% Nested
