rx_xyz2 = [(1:probe.N2)'*probe.N1*d0-62*lambda/2,zeros(probe.N2,2)];
% rx_xyz = [linspace(-probe.N*probe.pitch/2,probe.N*probe.pitch/2,probe.N)',zeros(probe.N,2)];
