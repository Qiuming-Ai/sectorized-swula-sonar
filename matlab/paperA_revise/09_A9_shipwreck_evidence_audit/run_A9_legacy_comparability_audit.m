function audit = run_A9_legacy_comparability_audit(result_dir)
%RUN_A9_LEGACY_COMPARABILITY_AUDIT Audit the three legacy Exp-8 scripts.
% This is a source-level reproducibility check. It does not execute the
% expensive CUDA echo simulation and does not modify the historical scripts.

this_dir = fileparts(mfilename('fullpath'));
package_root = fileparts(fileparts(fileparts(this_dir)));
sonarsim_dir = fullfile(this_dir, 'legacy_sources');
if nargin<1 || isempty(result_dir)
    result_dir = fullfile(package_root,'outputs','matlab','A9');
end
if ~exist(result_dir, 'dir')
    mkdir(result_dir);
end

names = ["dense", "cdm", "fdm"];
files = [ ...
    "PaperA_exp8_baseline_real_scene.m", ...
    "PaperA_exp8_cdm_real_scene.m", ...
    "PaperA_exp8_fdm_real_scene.m"];

code = strings(1, 3);
for k = 1:3
    source_path = fullfile(sonarsim_dir, files(k)+".txt");
    assert(exist(source_path, 'file') == 2, 'Missing source: %s', source_path);
    code(k) = string(fileread(source_path));
end

variable = [ ...
    "active_scene"; ...
    "receive_geometry"; ...
    "sparse_tx_spacing"; ...
    "field_of_view"; ...
    "pulse_duration"; ...
    "noise_injection"; ...
    "time_varying_gain"; ...
    "beamformer"; ...
    "decimation"; ...
    "manual_sector_gain"];

dense = [ ...
    "model1 + model3"; ...
    "128 elements, approximately 0.5 lambda"; ...
    "not applicable"; ...
    "-65 to 65 deg"; ...
    "5 ms"; ...
    "one AWGN call"; ...
    "enabled, K=10"; ...
    "fractional-delay"; ...
    "16"; ...
    "none"];

cdm = [ ...
    "model2 only"; ...
    "32 elements, approximately 1 lambda at 500 kHz"; ...
    "lambda/4"; ...
    "-60 to 60 deg"; ...
    "approximately 5.03 ms"; ...
    "four noisy copies summed"; ...
    "disabled"; ...
    "integer-delay"; ...
    "16"; ...
    "none"];

fdm = [ ...
    "model1 + model3"; ...
    "32 elements, approximately 1 lambda at 500 kHz"; ...
    "lambda/4"; ...
    "-60 to 60 deg"; ...
    "0.5 ms"; ...
    "four noisy copies summed"; ...
    "enabled, K=40"; ...
    "fractional-delay"; ...
    "40"; ...
    "sector 4 multiplied by 1.2"];

required = [ ...
    "identical saved scatterer list"; ...
    "128 at 0.5 lambda versus 32 at 2 lambda; aperture matched"; ...
    "12 elements at 0.5 lambda"; ...
    "-50 to 50 deg"; ...
    "5 ms for every method"; ...
    "one paired measured-AWGN realization"; ...
    "identical rule for every method"; ...
    "identical fractional-delay implementation"; ...
    "common physical output range grid"; ...
    "none"];

% Assertions make the audit fail loudly if the legacy sources change and the
% human-readable table above needs to be revisited.
assert(contains(code(1), 'models = {model1,model3};'));
assert(contains(code(2), 'models = {model2};'));
assert(contains(code(3), 'models = {model1,model3};'));
assert(contains(code(1), 'probe.N                 = 128'));
assert(contains(code(2), 'Nrx = 32'));
assert(contains(code(3), 'Nrx                 = 32'));
assert(contains(code(2), 'v_calc = v_calc_1+v_calc_2+v_calc_3+v_calc_4'));
assert(contains(code(3), 'v_calc = v_calc_1+v_calc_2+v_calc_3+v_calc_4'));
assert(contains(code(2), 'das_plane_wave_id'));
assert(contains(code(3), '1.2*beam{4}'));

comparable = false(size(variable));
reason = repmat("legacy scripts do not hold this control variable fixed", ...
    size(variable));
audit = table(variable, dense, cdm, fdm, required, comparable, reason);
writetable(audit, fullfile(result_dir, 'A9_legacy_comparability_audit.csv'));

fprintf('A9 source audit complete: %d/%d controls are comparable.\n', ...
    nnz(audit.comparable), height(audit));
fprintf('Result: %s\n', fullfile(result_dir, 'A9_legacy_comparability_audit.csv'));
fprintf('Methods inspected: %s\n', strjoin(names, ', '));
end
